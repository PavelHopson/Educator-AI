export interface PracticumAttempt { answer: string; submitted: string; checks: number[] }

export function planPracticum(gap: string, focus: string) {
  const requirement = gap.trim();
  if (!requirement) throw new Error('Добавьте одно требование, которое хотите отработать.');
  if (requirement.length > 600) throw new Error('Сократите требование до 600 символов.');
  const item = practicums.find(practicum => practicum.id === focus);
  if (!item) throw new Error('Выберите навык из двух доступных направлений. Для другого навыка подходящего практикума пока нет.');
  return { id: item.id, requirement, title: item.title };
}
export const emptyAttempt = (): PracticumAttempt => ({ answer: '', submitted: '', checks: [] });

export function submitAttempt(answer: string): PracticumAttempt {
  const trimmed = answer.trim();
  if (trimmed.length < 80) throw new Error('Опишите результат подробнее: минимум 80 символов. Это проверка заполнения, не оценка качества.');
  if (trimmed.length > 8000) throw new Error('Сократите ответ до 8000 символов.');
  return { answer, submitted: trimmed, checks: [] };
}

export function editAttempt(attempt: PracticumAttempt, answer: string): PracticumAttempt {
  return { ...attempt, answer, checks: [] };
}

export function canReview(attempt: PracticumAttempt): boolean {
  return Boolean(attempt.submitted) && attempt.answer.trim() === attempt.submitted;
}

export function practicumReport(id: string, attempt: PracticumAttempt, requirement = ''): string {
  const practicum = practicums.find(item => item.id === id);
  if (!practicum) throw new Error('Практикум не найден.');
  return [
    `УЧЕБНЫЙ ПРАКТИКУМ: ${practicum.title}`,
    'Оригинальное упражнение Educator-AI, вымышленная ситуация. Не стажировка, не работа и не сертификат работодателя. Независимой оценки нет.',
    `Требование для тренировки (выбрано пользователем): ${requirement.trim() || 'Не задано — свободная практика.'}`,
    'Выбор практикума сделан по указанному пользователем направлению, не по оценке резюме. Выполнение не закрывает требование автоматически: нужен собственный артефакт, его проверка и объяснение.',
    `Ситуация: ${practicum.situation}`, `Задание: ${practicum.task}`, `Результат: ${practicum.deliverable}`,
    `Последний ответ, открывший разбор:\n${attempt.submitted || 'Ещё не отправлен'}`,
    `Текущий ответ пользователя:\n${attempt.answer || 'Пусто'}`,
    canReview(attempt) ? 'Самооценка (отметки пользователя, не автоматическая проверка):' : 'Ответ изменён или не отправлен. Самооценка не завершена.',
    ...practicum.criteria.map((criterion, index) => `${canReview(attempt) && attempt.checks.includes(index) ? '[x]' : '[ ]'} ${criterion}`),
    `Следующий самостоятельный проект: ${practicum.transfer}`,
  ].join('\n\n');
}
